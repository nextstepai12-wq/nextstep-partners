async def mk(b,be,vp=None,mobile=False):
    ctx=await b.new_context(viewport=vp or {"width":1366,"height":900},is_mobile=mobile,has_touch=mobile,accept_downloads=True)
    pg=await ctx.new_page(); pg.errs=[]
    pg.on("pageerror",lambda e:pg.errs.append(str(e)))
    pg.on("console",lambda m: pg.errs.append("console:"+m.text) if m.type=="error" and "ERR_" not in m.text and "Failed to load resource" not in m.text else None)
    await pg.route(SB+"/**",be.handle)
    await pg.route("https://fonts.googleapis.com/**",lambda r:r.fulfill(status=200,content_type="text/css",body=""))
    return ctx,pg
